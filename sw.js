self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  // Bypass SW for video so Range requests work (seeking / progressive play)
  if (url.pathname.endsWith('.mp4') || e.request.headers.get('range')) {
    return; // network default
  }
  // Pages and data files: network first so a new deploy is never mixed with stale
  // cached copies (old book with new audio, etc.). Everything else: cache first.
  const fresh = e.request.mode === 'navigate' || /\.(html|json|js|css)$/.test(url.pathname) || url.pathname.endsWith('/');
  if (fresh) {
    e.respondWith(
      fetch(e.request).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
        return res;
      }).catch(() => caches.match(e.request))
    );
    return;
  }
  e.respondWith(
    caches.match(e.request).then((cached) =>
      cached ||
      fetch(e.request).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
        return res;
      }).catch(() => cached)
    )
  );
});
